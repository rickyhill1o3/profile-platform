-- Pokémon Center profile checkout-health history.
-- Run this once in the Supabase SQL editor before deploying the matching backend/frontend update.

create table if not exists public.pokemon_center_profile_events (
  id bigint generated by default as identity primary key,
  webhook_log_id text not null unique,
  user_id uuid not null references public.users(id) on delete cascade,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  event_at timestamptz not null default now(),
  category text not null check (category in ('success', 'payment_decline', 'other', 'profile_changed')),
  reason text not null default '',
  order_id text not null default '',
  account_email text not null default '',
  profile_name text not null default '',
  product text not null default '',
  sku text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists pokemon_center_profile_events_user_profile_time_idx
  on public.pokemon_center_profile_events (user_id, profile_id, event_at desc);

create index if not exists pokemon_center_profile_events_user_category_time_idx
  on public.pokemon_center_profile_events (user_id, category, event_at desc);

alter table public.pokemon_center_profile_events enable row level security;

-- No browser-facing policies are created. The backend service-role client owns all reads and
-- writes, and every API response is explicitly scoped to the signed-in user's user_id.
